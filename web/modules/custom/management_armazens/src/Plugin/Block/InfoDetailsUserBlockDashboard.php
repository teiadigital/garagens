  private function get_number_armazens_user(): int {
    $uid = \Drupal::currentUser()->id();

    $ids = \Drupal::entityQuery('node')
      ->accessCheck(FALSE)
      ->condition('type', 'armazem')
      ->condition('uid', $uid)
      ->execute();

    return count($ids);
  }

  private function get_bookings_raised(): int {
    $uid = \Drupal::currentUser()->id();

    return (int) \Drupal::database()
      ->select('garagem_reserva', 'gr')
      ->condition('gr.proprietario_id', $uid)
      ->countQuery()
      ->execute()
      ->fetchField();
  }

  private function get_bookings_made(): int {
    $uid = \Drupal::currentUser()->id();

    return (int) \Drupal::database()
      ->select('garagem_reserva', 'gr')
      ->condition('gr.user_id', $uid)
      ->countQuery()
      ->execute()
      ->fetchField();
  }

